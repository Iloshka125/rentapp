// Кэш для городов
let citiesCache = null;

// Функция для получения городов (с кэшированием)
export const getCities = async () => {
  console.log('🏙️ getCities вызвана');
  
  if (citiesCache) {
    console.log('🏙️ Возвращаем кэшированные города:', citiesCache.length);
    return citiesCache;
  }
  
  console.log('🏙️ Кэш пуст, загружаем города...');
  citiesCache = await fetchCities();
  console.log('🏙️ Города загружены в кэш:', citiesCache.length);
  return citiesCache;
};

// Функция для поиска городов по части названия
export const searchCities = async (query) => {
  const cities = await getCities();
  if (!query || query.trim().length === 0) {
    return cities.slice(0, 50); // Возвращаем первые 50 городов
  }
  
  const searchQuery = query.toLowerCase().trim();
  return cities
    .filter(city => city.toLowerCase().includes(searchQuery) && city.length <= 15)
    .slice(0, 20); // Ограничиваем результаты поиска
};

